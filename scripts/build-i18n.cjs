const fs = require('node:fs');
const vm = require('node:vm');
const langs = ['en', 'ko', 'zh', 'de', 'fi', 'pl', 'ru', 'tr', 'hy', 'ar'];
const phrases = fs.existsSync('locales/generated.json') ? JSON.parse(fs.readFileSync('locales/generated.json', 'utf8')) : {};
const authored = new Set();
for (const line of fs.readFileSync('locales/site.txt', 'utf8').split(/\r?\n/)) {
  if (!line.trim() || line.startsWith('#')) continue;
  const fields = line.split(' ⟐ ');
  if (fields.length !== langs.length) throw new Error(`Expected 10 columns: ${line}`);
  if (authored.has(fields[0])) throw new Error(`Duplicate phrase: ${fields[0]}`);
  authored.add(fields[0]);
  phrases[fields[0]] = Object.fromEntries(langs.map((lang, index) => [lang, fields[index]]));
}
// Existing explicit keys remain part of the same catalogue and review sheet.
const context = { window: {}, document: { addEventListener() {} } };
vm.createContext(context);
vm.runInContext(fs.readFileSync('js/i18n.js', 'utf8') + '\nglobalThis.dictionaries = TRANSLATIONS;', context);
for (const [key, source] of Object.entries(context.dictionaries.en)) {
  if (!phrases[source]) phrases[source] = Object.fromEntries(langs.map(lang => [lang, context.dictionaries[lang]?.[key] || source]));
}
// Translated labels retain their decorative arrow or icon.
for (const [source, values] of Object.entries(phrases)) {
  const match = source.match(/^([^\p{L}\p{N}]+)(.+)$/u);
  if (match && phrases[match[2]]) for (const lang of langs) if (lang !== 'en') values[lang] = match[1] + phrases[match[2]][lang];
}
if (fs.existsSync('locales/ko.json')) for (const [source, korean] of Object.entries(JSON.parse(fs.readFileSync('locales/ko.json','utf8')))) {
  if (!phrases[source]) phrases[source] = { en: source };
  phrases[source].ko = korean;
}
for (const [alias, source] of Object.entries({unknown:'Unknown', 'Player Not Found':'Player not found', 'Back To Games':'Back to Games'})) {
  if (phrases[alias] && phrases[source]) for (const lang of langs) if (lang !== 'en') phrases[alias][lang] = phrases[source][lang];
}
fs.writeFileSync('js/i18n-catalog.js', '// Generated by npm run build:i18n. Edit locales/site.txt.\nwindow.PBC_PHRASES = ' + JSON.stringify(phrases) + ';\n');
console.log(`Built ${Object.keys(phrases).length} multilingual phrases.`);
